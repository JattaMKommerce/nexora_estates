# every other language lives in <code>.txt next to this script:
#   label: / voice: (f5 | kokoro:<voice>:<lang> | video:<code>) / placeholder: / match: substring /
#   say: a=b | c=d (spoken form of written words) / words: a=b|c=d (visitor's words → English) /
#   own <id> <text> (a clip of its own when voice is video:<code>) / <id> <line>
def load_txt(path):
    L = {'lines': {}, 'sayMap': [], 'words': '', 'own': {}}
    for raw in open(path, encoding='utf-8'):
        line = raw.rstrip('\n')
        if not line.strip(): continue
        m = re.match(r'^(c\d{3}) (.+)$', line)
        if m: L['lines'][m.group(1)] = m.group(2).strip(); continue
        m = re.match(r'^own (c\d{3}) (.+)$', line)
        if m: L['own'][m.group(1)] = m.group(2).strip(); continue
        k, _, v = line.partition(':')
        k, v = k.strip(), v.strip()
        if k == 'say': L['sayMap'] += [tuple(x.split('=', 1)) for x in v.split(' | ') if '=' in x]
        elif k == 'words': L['words'] += '\n' + v
        elif k in ('label', 'voice', 'placeholder', 'match'): L[k] = v
    sm = L['sayMap']
    def say(t, sm=sm):
        for a, b in sm: t = t.replace(a.strip(), b.strip())
        return t
    L['say'] = say
    return L

